export const LABELS: Record<Language, Labels> = { en, kn }

/** Fills {name} placeholders: fill('Only {kg} left', { kg: '50 kg' }). */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match))
}

/** A friendly message for an engine error, in the screen language; falls back to the engine's own message. */
export function errorText(t: Labels, error: DomainError): string {
  const known = (t.errors as Record<string, string>)[error.code]
  return known ?? fill(t.errors.generic, { message: error.message })
}
